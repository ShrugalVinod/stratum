// Number-consistency list (build prompt §4.1): every number the site shows, with where it comes
// from, so the team can check it against the brief, Lean Canvas and video script.
//
//   node --experimental-strip-types scripts/check_numbers.ts [--ref brief.txt ...] [--out file.md]
//
// 1. Numbers in the copy: string literals of src/content/site.ts and visible JSX text of
//    src/pages/*.tsx and src/components/*.tsx (CSS, imports and code are skipped).
// 2. Numbers computed from the exported data build (public/data/<current>/): what the map shows.
// 3. With --ref text files (the brief etc.), each copy number is marked "found" if the same number
//    appears in any of them. "not found" does not mean wrong; it means a person should look.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const args = process.argv.slice(2);
const refs: string[] = [];
let out: string | null = null;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--ref") refs.push(args[++i]);
  else if (args[i] === "--out") out = args[++i];
}
const refText = refs.map((f) => readFileSync(f, "utf8")).join("\n").replace(/(\d),(\d{3})/g, "$1$2");

const NUM = /\d(?:[\d,]*\d)?(?:\.\d+)?(?:\s?(?:%|°[NE]?|km|h|K|ft|MB|min|µm|hPa|GB))?/g;
// skip dates, years, file names and phase/FL labels that are identifiers, not claims
const SKIP = /^(?:20\d\d|19\d\d)$|^0\d$/;

type Row = { where: string; number: string; context: string; found?: boolean };

function numbersIn(text: string, where: string): Row[] {
  const rows: Row[] = [];
  for (const m of text.matchAll(NUM)) {
    const n = m[0].trim();
    const bare = n.replace(/[^\d.,]/g, "").replace(/,/g, "");
    if (SKIP.test(bare) || bare.length === 0) continue;
    const i = m.index ?? 0;
    const context = text.slice(Math.max(0, i - 45), i + n.length + 45).replace(/\s+/g, " ").trim();
    const row: Row = { where, number: n, context };
    if (refs.length) row.found = new RegExp(`(^|[^\\d.])${bare.replace(".", "\\.")}([^\\d]|$)`).test(refText);
    rows.push(row);
  }
  return rows;
}

function lineOf(src: string, idx: number): number {
  return src.slice(0, idx).split("\n").length;
}

const rows: Row[] = [];
// 1a. site.ts string literals
{
  const f = "src/content/site.ts";
  const src = readFileSync(join(ROOT, f), "utf8");
  for (const m of src.matchAll(/"((?:[^"\\]|\\.)*)"/g)) {
    if (/^(?:\/|\.|https?:|[a-z_]+$|#)/.test(m[1])) continue; // paths, urls, keys
    rows.push(...numbersIn(m[1], `${f}:${lineOf(src, m.index ?? 0)}`));
  }
}
// 1b. visible JSX text in pages and components
for (const dir of ["src/pages", "src/components"]) {
  for (const name of readdirSync(join(ROOT, dir)).filter((n) => n.endsWith(".tsx"))) {
    const f = `${dir}/${name}`;
    const src = readFileSync(join(ROOT, f), "utf8");
    for (const m of src.matchAll(/>([^<>{}]*\d[^<>{}]*)</g)) {
      const t = m[1].trim();
      if (!t || /[;=?]|=>|\bconst\b|\bimport\b/.test(t)) continue;
      rows.push(...numbersIn(t, `${f}:${lineOf(src, m.index ?? 0)}`));
    }
  }
}

// 2. numbers computed from the data build
const dataDir = join(ROOT, "public/data");
const build = JSON.parse(readFileSync(join(dataDir, "current.json"), "utf8")).build as string;
const man = JSON.parse(readFileSync(join(dataDir, build, "manifest.json"), "utf8"));
const dataRows: [string, string | number][] = [
  ["data build", build],
  ["days with contrail-condition grids", man.days.length],
  ["flight levels per day", man.flight_levels.length],
  ["hours per day", man.hours_utc.length],
  ["grid", `${man.grid.rows} × ${man.grid.cols} cells, ${man.grid.step_deg}°`],
  ["study domain", `${man.grid.lat_south}–${man.grid.lat_north}°N, ${man.grid.lon_west}–${man.grid.lon_east}°E`],
  ["days with flights", man.days_with_flights.join(", ")],
];
for (const d of man.days_with_flights as string[]) {
  const dj = JSON.parse(readFileSync(join(dataDir, build, "days", d, "day.json"), "utf8"));
  const segs = JSON.parse(readFileSync(join(dataDir, build, "days", d, "segments_flagged.json"), "utf8")) as { flight_id: string }[];
  dataRows.push([`${d}: commercial flights on the map`, dj.n_flights]);
  dataRows.push([`${d}: one-minute segments`, dj.n_segments]);
  dataRows.push([`${d}: flagged persistent-contrail segments (B1)`, dj.n_flagged]);
  dataRows.push([`${d}: flights with a flagged segment`, new Set(segs.map((s) => s.flight_id)).size]);
}

const md: string[] = [
  "# STRATUM website: number-consistency list",
  "",
  `Generated by \`web/scripts/check_numbers.ts\` from the site source and data build \`${build}\`.`,
  "Check each number against the brief, Lean Canvas and video script; fix the copy (src/content/site.ts) or the brief.",
  refs.length ? `Reference files searched: ${refs.map((r) => "`" + r.split("/").pop() + "`").join(", ")}.` : "",
  "",
  "## From the data (what the map shows)",
  "",
  "| item | value |",
  "|---|---|",
  ...dataRows.map(([k, v]) => `| ${k} | ${typeof v === "number" ? v.toLocaleString("en-GB") : v} |`),
  "",
  "## In the website copy",
  "",
  refs.length ? "| number | in brief? | context | source |" : "| number | context | source |",
  refs.length ? "|---|---|---|---|" : "|---|---|---|",
  ...rows.map((r) =>
    refs.length
      ? `| ${r.number} | ${r.found ? "found" : "**not found**"} | ${r.context.replace(/\|/g, "/")} | ${r.where} |`
      : `| ${r.number} | ${r.context.replace(/\|/g, "/")} | ${r.where} |`,
  ),
  "",
];
const text = md.join("\n");
if (out) writeFileSync(out, text);
else process.stdout.write(text);
if (out) console.log(`${rows.length} copy numbers, ${dataRows.length} data items → ${out}${existsSync(out) ? "" : ""}`);
